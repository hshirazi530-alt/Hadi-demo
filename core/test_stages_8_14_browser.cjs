const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const { strict: assert } = require('node:assert');
const { tmpdir } = require('node:os');
const { join } = require('node:path');
const base = process.env.HADI_TEST_URL || 'http://127.0.0.1:8000';
const exe = process.env.HADI_CHROMIUM || undefined;
(async () => {
  const browser = await chromium.launch({ executablePath: exe, headless: true, args: ['--no-sandbox'] });
  const page = await browser.newPage({ viewport: { width: 1440, height: 900 }, reducedMotion: 'reduce' });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.route(/^https?:\/\/(?!127\.0\.0\.1)/, route => route.abort());
  await page.goto(base + '/', { waitUntil: 'domcontentloaded' });
  await page.waitForTimeout(1300);
  for (const width of [320,360,375,390,414,480,768,820,1024,1280,1440,1920]) {
    await page.setViewportSize({ width, height: 900 });
    await page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))));
    const values = await page.evaluate(() => {
      const banner = document.querySelector('#hm-collection-banner').getBoundingClientRect();
      const social = document.querySelector('.hm-header-social').getBoundingClientRect();
      const header = document.querySelector('.hm-utility__inner').getBoundingClientRect();
      const labels = [...document.querySelectorAll('.hm-header-social a')].map(a => {
        const r = a.getBoundingClientRect();
        return { x:r.x, right:r.right, y:r.y, bottom:r.bottom, label:a.getAttribute('aria-label'), display:getComputedStyle(a).display };
      });
      return { scrollWidth:document.documentElement.scrollWidth, width:innerWidth, banner:{x:banner.x,width:banner.width,right:banner.right}, social:{x:social.x,right:social.right,width:social.width,height:social.height}, header:{x:header.x,right:header.right}, labels };
    });
    assert(values.scrollWidth <= width + 1, `horizontal overflow at ${width}: ${JSON.stringify(values)}`);
    assert(Math.abs(values.banner.x) < 2 && Math.abs(values.banner.width - width) < 2, `banner not full width at ${width}: ${JSON.stringify(values.banner)}`);
    assert(values.social.width > 50 && values.social.x >= -1 && values.social.right <= width+1, `social not visible at ${width}: ${JSON.stringify(values.social)}`);
    for (const icon of values.labels) assert(icon.label && icon.display !== 'none' && icon.x >= -1 && icon.right <= width+1, `bad icon at ${width}: ${JSON.stringify(icon)}`);
    assert.equal(await page.locator('.faq-section').count(), 0);
  }
  await page.setViewportSize({ width:1440,height:900 });
  await page.locator('#contact-phone').fill('۰۹۱۲۱۲۳۴۵۶۷');
  assert.equal(await page.locator('#contact-phone').inputValue(), '121234567');
  assert.equal(await page.locator('#contact-phone').evaluate(e => e.checkValidity()), true);
  await page.locator('#contact-phone').fill('12345678');
  assert.equal(await page.locator('#contact-phone').evaluate(e => e.checkValidity()), false);
  await page.locator('#contact-phone').fill('+989121234567');
  assert.equal(await page.locator('#contact-phone').inputValue(), '121234567');
  await page.locator('[data-helper-toggle]').click();
  assert.equal(await page.locator('[data-helper-toggle]').getAttribute('aria-expanded'), 'true');
  await page.locator('[data-helper-choice="warranty"]').click();
  assert(await page.locator('[data-helper-answer="warranty"]').isVisible());
  await page.keyboard.press('Escape');
  assert.equal(await page.locator('[data-helper-toggle]').getAttribute('aria-expanded'), 'false');
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.waitForTimeout(250);
  const menu = page.locator('[data-category-menu]');
  await menu.locator('summary').hover();
  assert.equal(await menu.evaluate(el => el.open), true);
  const links = menu.locator('[data-category-target]');
  if (await links.count() > 1) {
    const second = links.nth(1);
    await second.hover();
    const target = await second.getAttribute('data-category-target');
    assert(await page.locator('#' + target).isVisible(), 'hover did not reveal second panel');
  }
  await page.keyboard.press('Escape');
  assert.equal(await menu.evaluate(el => el.open), false);
  await page.goto(base + '/product/c2gahe5ea1/', { waitUntil:'domcontentloaded' });
  await page.waitForTimeout(1200);
  assert(await page.locator('[data-authenticity-wrap]').isVisible());
  assert((await page.locator('[data-authenticity-wrap]').innerText()).includes('های‌کپی'));
  assert(await page.locator('[data-warranty-option]').count() >= 2);
  const cartResponse = page.waitForResponse(r => r.url().includes('/add-to-cart/') && r.request().method() === 'POST');
  await page.locator('.store-product-info .product-cart-btn').click();
  assert.equal((await cartResponse).status(), 200);
  await page.goto(base + '/cart/', { waitUntil:'domcontentloaded' });
  await page.waitForTimeout(1000);
  const checkoutMobile = page.locator('#checkout-mobile');
  assert(await checkoutMobile.isVisible());
  await checkoutMobile.fill('09121234567');
  assert.equal(await checkoutMobile.inputValue(), '121234567');
  assert.equal(await checkoutMobile.evaluate(e => e.checkValidity()), true);
  await checkoutMobile.fill('12123456');
  assert.equal(await checkoutMobile.evaluate(e => e.checkValidity()), false);
  assert.equal(errors.length, 0, `page errors: ${errors.join('; ')}`);
  await page.goto(base + '/', { waitUntil:'domcontentloaded' });
  await page.waitForTimeout(1100);
  await page.screenshot({path:join(tmpdir(), 'stages-8-14-desktop.png')});
  await page.setViewportSize({width:375,height:850});
  const mobileTrigger = page.locator('button.burger-icon');
  await mobileTrigger.focus();
  await page.keyboard.press('Enter');
  assert(await page.locator('.mobile-header-active').evaluate(el => el.classList.contains('sidebar-visible')), 'mobile menu did not open with Enter');
  await page.locator('.mobile-menu-close').click();
  await page.screenshot({path:join(tmpdir(), 'stages-8-14-mobile.png')});
  console.log('PASS 12 widths, edge-to-edge banner, header icons, no homepage FAQ, phone validation/paste on contact and demo cart, local guide, category hover+Escape, mobile keyboard menu, authenticity and warranty.');
  await browser.close();
})().catch(error => { console.error(error); process.exit(1); });
